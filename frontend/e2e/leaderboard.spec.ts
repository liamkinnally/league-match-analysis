import { expect, test } from "@playwright/test";
import { installDeterministicGameAssets } from "./support/game-assets";

test("cached NA leaderboard opens profiles only on click and stays readable on mobile", async ({ page, request }) => {
  await installDeterministicGameAssets(page);
  const lookups: string[] = [], leaderboardRequests: string[] = [], errors: string[] = [];
  page.on("request", req => {
    const path = new URL(req.url()).pathname;
    if (path.startsWith("/api/player-matches")) lookups.push(req.url());
    if (path === "/api/leaderboard") leaderboardRequests.push(req.url());
  });
  page.on("pageerror", error => errors.push(error.message));
  await page.goto("/");
  await page.getByRole("navigation", { name: "Product navigation" }).getByRole("link", { name: "Leaderboard" }).click();
  await expect(page).toHaveURL(/\/leaderboard$/);
  await expect(page.getByRole("link", { name: "Leaderboard", exact: true })).toHaveAttribute("aria-current", "page");
  const table = page.getByRole("table", { name: "North America ranked Solo/Duo standings" });
  await expect(table.getByRole("row")).toHaveCount(101);
  await expect(page.getByRole("heading", { name: "Estimated promotion cutoffs" })).toBeVisible();
  await expect(page.getByText("300 slots", { exact: true })).toBeVisible();
  await expect(page.getByText("700 slots", { exact: true })).toBeVisible();
  const player = table.getByRole("link", { name: /History100\s*#NA1/ });
  await expect(player).toHaveAttribute("href", "/summoners/na/History100-NA1");
  const icon = table.getByRole("row").nth(1).locator(".leaderboard__player img");
  await expect.poll(() => icon.evaluate((image: HTMLImageElement) => image.complete && image.naturalWidth > 0)).toBe(true);
  const initialLeaderboardRequests = leaderboardRequests.length;
  expect(initialLeaderboardRequests).toBeGreaterThan(0);
  const pagination = page.getByRole("navigation", { name: "Leaderboard pages" });
  await pagination.getByRole("button", { name: "Page 2", exact: true }).click();
  await expect(table.getByRole("row").nth(1).getByRole("cell").first()).toHaveText("101");
  await expect(table).toBeFocused();
  await pagination.getByRole("button", { name: "Page 3", exact: true }).click();
  await expect(table.getByRole("row")).toHaveCount(101);
  await expect(table.getByRole("row").nth(1).getByRole("cell").first()).toHaveText("201");
  await expect(table.getByRole("row").last().getByRole("cell").first()).toHaveText("300");
  await expect(pagination.getByRole("button", { name: "Page 3", exact: true })).toHaveAttribute("aria-current", "page");
  await expect(table.getByText("Player name pending")).toBeVisible();
  await expect(table.getByText("Player name pending").locator("xpath=ancestor::a")).toHaveCount(0);
  await pagination.getByRole("button", { name: "Page 1", exact: true }).click();
  expect(leaderboardRequests).toHaveLength(initialLeaderboardRequests);
  await expect(table.getByRole("row").nth(1)).toContainText("75.0%");
  const response = await request.get("/api/leaderboard");
  expect(response.ok()).toBe(true);
  expect(await response.text()).not.toMatch(/puuid|payload_json|sourceCapture|token/);
  await page.screenshot({ path: "test-results/leaderboard-desktop.png", fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await player.focus();
  await expect(player).toBeFocused();
  await page.screenshot({ path: "test-results/leaderboard-mobile.png", fullPage: true });
  expect(lookups).toEqual([]);
  await player.click();
  await expect(page).toHaveURL(/\/summoners\/na\/History100-NA1$/);
  await expect(page.getByRole("heading", { level: 1 })).toHaveText("History100#NA1");
  await expect(page.getByRole("list", { name: "Recent match history" })).toBeVisible({ timeout: 20000 });
  expect(lookups.length).toBeGreaterThan(0);
  expect(errors).toEqual([]);
});
